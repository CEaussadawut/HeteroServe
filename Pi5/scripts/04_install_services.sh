#!/usr/bin/env bash
# 04 -- install and enable the node's systemd units.
#   heteroserve-prepare    re-applies the governor/fan/swap pins at every boot
#   heteroserve-rpc        llama.cpp rpc-server, the actual compute service
#   heteroserve-agent      small HTTP control/health endpoint for the orchestrator
#   heteroserve-telemetry  thermal/clock/memory sampler on the harness time base
. "$(dirname "$0")/lib/common.sh"
load_env
need_root "$@"

# --- resolve the rpc-server interface this build actually exposes -----------------
# Upstream has changed this interface twice, and the pinned SHA is chosen on the
# Jetson (CUDA 10.2 constrains the whole cluster), so detect it rather than assume:
#   * the binary was renamed rpc-server -> ggml-rpc-server in c299a92 (2026-06-27)
#   * -m/--mem was removed in 41386cf (2025-10-17)
#   * -c/--cache has ALWAYS been boolean -- it takes no directory. LLAMA_CACHE picks
#     the location, and the server appends "rpc/" to it.
# Getting this wrong is not a soft failure: rpc-server prints "error: unknown
# argument" and then calls exit(0), which systemd reads as a clean shutdown.
RPC_BIN=""
for cand in ggml-rpc-server rpc-server; do
  if [ -x "${LLAMA_BIN}/${cand}" ]; then RPC_BIN="${LLAMA_BIN}/${cand}"; break; fi
done
if [ -z "$RPC_BIN" ]; then
  die "no rpc-server binary in ${LLAMA_BIN} (looked for ggml-rpc-server, then rpc-server) -- run 02_build_llama_cpp.sh first"
fi
ok "rpc binary: $(basename "$RPC_BIN")"

RPC_HELP="$("$RPC_BIN" --help 2>&1 || true)"
RPC_EXTRA_ARGS=""
ADVERTISED="actual free memory (this build has no --mem)"
case "$RPC_HELP" in
  *--mem*)
    RPC_EXTRA_ARGS="--mem ${RPC_MEM_MB}"
    ADVERTISED="${RPC_MEM_MB} MB"
    ok "build accepts --mem; advertising ${RPC_MEM_MB} MB to the placement engine" ;;
  *)
    warn "this build has NO --mem (removed upstream 2025-10-17 in 41386cf)."
    warn "The node will advertise its ACTUAL free memory instead of the deliberate"
    warn "${RPC_MEM_MB} MB headroom figure in node.env, so the placement engine can be"
    warn "handed a partition with no slack. Record this in the node card, or pin to a"
    warn "revision older than 41386cf." ;;
esac
case "$RPC_HELP" in
  *--cache*) RPC_EXTRA_ARGS="${RPC_EXTRA_ARGS} --cache" ;;
  *) warn "this build has no --cache; the local file cache stays disabled" ;;
esac

log "generating the rpc-server launcher from the detected interface"
install -d -m 0755 /opt/heteroserve/bin "$RPC_CACHE_DIR" "$DATA_DIR"
LAUNCHER=/opt/heteroserve/bin/rpc-server.sh
{
  echo '#!/bin/sh'
  echo "# GENERATED by 04_install_services.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ) -- do not edit."
  echo "# Re-run 04_install_services.sh after any rebuild to regenerate it."
  echo "# Detected binary : ${RPC_BIN}"
  echo "# Detected flags  : ${RPC_EXTRA_ARGS:-<none>}"
  echo "# -c/--cache takes NO argument; LLAMA_CACHE selects where it writes."
  echo 'set -e'
  echo "export LLAMA_CACHE=\"${RPC_CACHE_DIR}\""
  echo 'mkdir -p "$LLAMA_CACHE"'
  echo "exec \"${RPC_BIN}\" --host \"${RPC_HOST}\" --port \"${RPC_PORT}\" ${RPC_EXTRA_ARGS}"
} > "$LAUNCHER"
chmod 0755 "$LAUNCHER"
ok "wrote ${LAUNCHER}"
sed 's/^/    /' "$LAUNCHER"

log "publishing node.env to /etc/heteroserve/node.env (units read it from there)"
install -d -m 0755 /etc/heteroserve
install -m 0644 "$HS_CONFIG" /etc/heteroserve/node.env

log "installing the python node services to /opt/heteroserve/node"
install -d -m 0755 /opt/heteroserve/node
install -m 0644 "${HS_NODE_DIR}/node/"*.py /opt/heteroserve/node/

log "installing unit files"
for u in "${HS_NODE_DIR}/systemd/"*.service; do
  install -m 0644 "$u" /etc/systemd/system/
  ok "$(basename "$u")"
done
systemctl daemon-reload

for u in heteroserve-prepare heteroserve-rpc heteroserve-agent heteroserve-telemetry; do
  systemctl enable --now "${u}.service"
done

sleep 2
systemctl --no-pager --lines=0 status heteroserve-rpc heteroserve-agent heteroserve-telemetry || true
ok "services installed; rpc-server on ${RPC_HOST}:${RPC_PORT} advertising ${ADVERTISED}"
